"""Show how far installation, maintenance and troubleshooting guide investigations
have progressed.

The browser needs to distinguish completed guides from proposed finishes, failed
reviews and work that has not started. This file reads saved progress and evidence
for those counts. It neither generates instructions nor changes a guide's status."""

import json

KINDS = ("installation", "troubleshooting", "maintenance")
FINISHED = {"finished", "finished_with_gaps"}


def read_saved(path, default):
    """Read an optional atomic checkpoint for a read-only progress snapshot.

    Args:
        path: Application-owned path; never constructed from model text.
        default: Value returned before the checkpoint has been written.
    Returns:
        Decoded JSON or default when absent. Corrupt records raise rather than invent progress.
    """
    return json.loads(path.read_text()) if path.exists() else default


def summarize_guide_investigations(path, detail):
    """Group observed tasks, collected evidence and genuine finish outcomes by guide kind.

    Args:
        path: Existing job directory with coordinator and per-task checkpoints.
        detail: Current state, saved profile, document and audit events from the detail route.
    Returns:
        Three category records with actual denominators or unknown totals before discovery.
        Includes extracted-fact indexes, source IDs and planner-reported questions. A finish
        proposal is distinct from reviewed completion; failed or exhausted work never counts
        as finished. Historical needs-review results without a finish marker remain uncertain.
        Reads only; no model calls, checkpoint migration or inference from elapsed time.
    """
    candidates_path = path / "procedure-candidates-v2.json"
    discovered = candidates_path.exists()
    candidates = read_saved(candidates_path, {}).get("candidates", [])
    profile = detail.get("profile") or {}
    published = {g["id"]: g for g in profile.get("procedure_guides", [])}
    published.update(
        {
            g["id"]: g
            for g in read_saved(path / "procedure-guides-progress.json", {}).get(
                "guides", []
            )
        }
    )
    # Historical saved guides remain inspectable even if discovery files were retired.
    known = {c["id"] for c in candidates}
    candidates = candidates + [g for i, g in published.items() if i not in known]
    actions = {}
    finish_signals = set()
    for event in detail.get("audit", []):
        if event.get("kind") == "procedure_decision":
            actions[event["procedure_id"]] = event
            if event.get("action") == "finish":
                finish_signals.add(event["procedure_id"])
    active = detail["state"]["status"] == "analyzing"
    groups = []
    for kind in KINDS:
        tasks, evidence = [], set()
        for candidate in candidates:
            if candidate["kind"] != kind:
                continue
            task_id = candidate["id"]
            # IDs are generated by application code; refuse unexpected paths in old artifacts.
            if not task_id or any(
                c not in "abcdefghijklmnopqrstuvwxyz0123456789-" for c in task_id
            ):
                continue
            saved = read_saved(path / "procedure-plans-v3" / f"{task_id}.json", {})
            recovered = read_saved(
                path / "procedure-repairs-v1" / f"{task_id}.json", {}
            )
            if recovered:
                saved = recovered
            failure = read_saved(path / f"procedure-failure-{task_id}.json", {})
            result = (
                failure.get("result") or saved.get("result") or published.get(task_id)
            )
            evidence.update(saved.get("evidence", {}))
            if result:
                evidence.update(result.get("inspected_source_ids", []))
            action = actions.get(task_id, {})
            if result and result.get("generation_failed"):
                status = "failed"
            elif result and result.get("completion"):
                status = result["completion"]
            elif result and result.get("status") == "source_checked":
                status = "finished"
            elif result:
                status = (
                    "unfinished"
                    if result.get("status") == "unfinished"
                    else "saved_needs_review"
                )
            elif not saved:
                status = "queued" if active else "not_started"
            elif not active:
                status = (
                    "paused" if detail["state"]["status"] == "paused" else "stopped"
                )
            else:
                status = (
                    "checking_finish"
                    if action.get("action") == "finish"
                    else "investigating"
                )
            tasks.append(
                {
                    "id": task_id,
                    "title": candidate["title"],
                    "status": status,
                    "finish_proposed": task_id in finish_signals,
                    "decisions": saved.get("decisions", 0),
                    "inspections": saved.get("inspections", 0),
                    "reviews": saved.get("reviews", 0),
                    "latest_action": action.get("action"),
                    "latest_reason": action.get("reason", ""),
                    "questions": saved.get(
                        "questions", (result or {}).get("question_ledger", [])
                    ),
                    "gaps": (result or {}).get("unanswered_questions", []),
                    "issues": (result or {}).get(
                        "review_issues", saved.get("problems", [])
                    ),
                    "guide_saved": bool(
                        result and result.get("status") != "unfinished"
                    ),
                }
            )
        finished = sum(t["status"] in FINISHED for t in tasks)
        total = len(tasks) if discovered else None
        if total == 0:
            status = "no_tasks"
        elif tasks and finished == len(tasks) and discovered:
            status = (
                "finished_with_gaps"
                if any(t["status"] == "finished_with_gaps" for t in tasks)
                else "finished"
            )
        elif any(t["status"] in {"investigating", "checking_finish"} for t in tasks):
            status = "working"
        elif any(
            t["status"]
            in {
                "failed",
                "allowance_exhausted",
                "stopped_before_completion",
                "review_unresolved",
                "stopped",
                "unfinished",
            }
            for t in tasks
        ):
            status = "incomplete"
        elif any(t["status"] == "saved_needs_review" for t in tasks):
            status = "needs_review"
        elif any(t["status"] == "paused" for t in tasks):
            status = "paused"
        else:
            status = "queued" if discovered else "discovering"
        groups.append(
            {
                "kind": kind,
                "status": status,
                "finished": finished,
                "total": total,
                "saved_guides": sum(t["guide_saved"] for t in tasks),
                "evidence_ids": sorted(evidence),
                "fact_indexes": [
                    i
                    for i, fact in enumerate(profile.get("facts", []))
                    if fact.get("evidence_id") in evidence
                ],
                "tasks": tasks,
            }
        )
    return groups
