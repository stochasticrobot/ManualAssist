class InlineWorker:
    """Settle a submitted production task before the test observes its state."""

    def submit(self, function, *args):
        """Execute the real workflow synchronously in isolated storage.

        Args:
            function: Production worker callback selected by the HTTP endpoint.
            *args: Callback arguments from the endpoint.
        Returns:
            Callback result; does not create a background thread or network request.
        """
        return function(*args)


class ManualModel:
    """Fixture provider returning source-based facts, one diagnostic path and an FAQ."""

    provider = "fixture"
    model = "manual"
    capabilities = Capabilities(images=True, max_output_tokens=8000)

    @local_evidence_reply
    def generate(self, request):
        """Respond to real workflow prompts without an external provider.

        Args:
            request: Neutral request generated by the production orchestrator.
        Returns:
            Measured fixture response; asserts no document-wide review prompt is sent.
            Tests routing, topology and persistence, not live reasoning quality.
        """
        title = request.schema["title"]
        if title == "InspectionDecision":
            body = {
                "document_type": "appliance manual",
                "purpose": "Troubleshooting",
                "action": "finish",
                "reason": "Proceed to complete extraction",
                "page": 1,
                "query": "",
                "evidence_id": "",
            }
        elif title == "FactExtraction":
            assert set(request.schema["properties"]) == {"facts"}
            body = {"facts": []}
        elif title == "ProcedureCandidates":
            body = {"procedures": []}
        elif title == "UncertaintyCandidates":
            assert set(request.schema["properties"]) == {"findings"}
            body = {"findings": []}
        elif title in ("FAQGeneration", "TroubleshootingChecksGeneration"):
            items = fixture_payload(request)["source"]
            item = next((i for i in items if "If E1 persists, stop use and contact service." in i["text"]), items[0])
            citation = {
                "evidence_id": item["id"],
                "quote": "If E1 persists, stop use and contact service.",
            }
            body = {"faq": [], "troubleshooting": []}
            if citation["quote"] in item["text"]:
                body["faq"] = [
                    {
                        "question": "What if E1 persists?",
                        "answer": "Stop use and contact service.",
                        "applies_to": "Model A",
                        "citations": [citation],
                    }
                ]
                body["troubleshooting"] = [
                    {
                        "symptom": "Persistent E1",
                        "applies_to": "Model A",
                        "prerequisites": [],
                        "root": "check",
                        "nodes": [
                            {
                                "id": "check",
                                "kind": "check",
                                "text": "Does E1 persist?",
                                "citations": [citation],
                                "branches": [
                                    {
                                        "condition": "E1 persists",
                                        "next_node": "service",
                                        "citations": [citation],
                                    }
                                ],
                            },
                            {
                                "id": "service",
                                "kind": "stop",
                                "text": "Stop use and contact service.",
                                "citations": [citation],
                                "branches": [],
                            },
                        ],
                    }
                ]
            if title == "FAQGeneration":
                body.pop("troubleshooting")
                assert set(request.schema["properties"]) == {"faq"}
            else:
                body = {"troubleshooting_checks": [dict(symptom="Persistent E1", applies_to="Model A", instruction=citation["quote"], citations=[citation])] if citation["quote"] in item["text"] else []}
                assert set(request.schema["properties"]) == {"troubleshooting_checks"}
        else:
            raise AssertionError(title)
        if title == "InspectionDecision":
            body["remaining_questions"] = []
        return Result(json.dumps(body), self.provider, self.model, "complete", 100, 50)


@pytest.mark.parametrize("bounded", [True, False])
def test_large_manual_pauses_resumes_and_exports_guidance(
    tmp_path, monkeypatch, bounded
):
    """Run a >100k-character manual through real HTTP start/resume and publication.

    Args:
        tmp_path: Isolated job and export storage.
        monkeypatch: Replaces model transport, executor and vector-writing dependency.
        bounded: Exercise small-slice recovery when True, or full default completion otherwise.
    Returns:
        None; proves continuation reuses checkpoints, reaches final batches and writes
        cited trees/FAQ. No live model, Docling or Chroma quality is claimed here.
    """
    if bounded:
        monkeypatch.setattr(
            analysis,
            "Run",
            lambda job_id, service=None, replay=False: calls.Run(
                job_id, limit=12, service=service, replay=replay
            ),
        )
    monkeypatch.setattr(storage, "JOBS", tmp_path / "jobs")
    monkeypatch.setattr(runtime, "WORKER", InlineWorker())
    monkeypatch.setattr(
        calls,
        "configured_service",
        lambda: ModelService({"text": ManualModel(), "vision": ManualModel()}),
    )

    def fake_index(job_id, document):
        """Persist source manifests while substituting only vector storage.

        Args:
            job_id: Isolated workflow job.
            document: Complete parsed fixture, including its last source batch.
        Returns:
            Persisted source chunks without embeddings or remote calls.
        """
        chunks = [
            {
                "id": i["id"],
                "text": i["text"],
                "page": i["page"],
                "evidence_id": i["id"],
            }
            for i in document["items"]
        ]
        storage.save(storage.job_dir(job_id) / "chunks.json", chunks)
        return chunks

    monkeypatch.setattr(index, "build", fake_index)
    with TestClient(app) as client:
        job = storage.create("large.pdf", b"%PDF-fixture")
        path = storage.job_dir(job["id"])
        items = [
            {
                "id": f"e{i}",
                "text": (
                    "If E1 persists, stop use and contact service. " if i == 59 else ""
                )
                + "Source text. " * 150,
                "label": "text",
                "page": i + 1,
                "section": [],
            }
            for i in range(60)
        ]
        document = {
            "pages": 60,
            "items": items,
            "outline": [],
            "tables": [],
            "figures": [],
            "parser_status": "success",
        }
        storage.save(path / "document.json", document)
        storage.update(job["id"], status="parsed", pages=60, tables=0, figures=0)
        endpoint = f"/api/jobs/{job['id']}"
        assert client.post(endpoint + "/analyze").status_code == 200
        first = client.get(endpoint).json()
        assert first["state"]["status"] == ("paused" if bounded else "ready")
        checkpoint = (path / "facts-checkpoint.json").read_bytes()
        prior_response = (path / "call-002-response.json").read_bytes()
        final = first
        if bounded:
            assert 0 < first["workflow"]["progress"]["completed_batches"] < 30
            for _ in range(30):
                assert client.post(endpoint + "/resume").status_code == 200
                final = client.get(endpoint).json()
                if final["state"]["status"] != "paused":
                    break
        assert final["state"]["status"] == "ready"
        assert final["profile"]["batches_processed"] == 30
        assert len(final["chunks"]) == 60
        assert (path / "call-002-response.json").read_bytes() == prior_response
        assert final["state"]["calls"] == 120
        from collections import Counter

        counts = Counter(
            json.loads(p.read_text())["schema"]["title"]
            for p in path.glob("call-*-request.json")
        )
        assert counts == {
            "FactExtraction": 30,
            "UncertaintyCandidates": 15,
            "ProcedureCandidates": 15,
            "FAQGeneration": 30,
            "TroubleshootingChecksGeneration": 30,
        }
        assert final["profile"]["faq"][0]["citations"][0]["page"] == 60
        check = client.get(endpoint + "/assets/troubleshooting_checks.json").json()[0]
        assert check["instruction"] == "If E1 persists, stop use and contact service."
        assert final["profile"]["troubleshooting"] == []
        report = client.get(endpoint + "/assets/report.html").text
        assert "Stop use and contact service." in report and "#page=60" in report
        assert b"faq" in (path / "facts-checkpoint.json").read_bytes()
        assert (checkpoint != (path / "facts-checkpoint.json").read_bytes()) == bounded
